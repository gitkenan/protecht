// Package core contains the platform-independent domain model and the
// validation rules of the protecht evidence/event protocol. It has no
// knowledge of HTTP, storage, or any device platform specifics.
package core

import "time"

// Device is a registered client of the system. The Token is issued at
// registration and authenticates all subsequent write calls. Only its
// SHA-256 hash is persisted; the plaintext token is returned exactly once,
// in the registration response.
type Device struct {
	ID        string    `json:"id"`
	Name      string    `json:"name"`
	Token     string    `json:"token,omitempty"`
	CreatedAt time.Time `json:"created_at"`
}

// Evidence is a single artifact (photo, screenshot, note, ...) uploaded by a
// device. Integrity is anchored by SHA256, the hex-encoded hash of Content.
// ContentType is sniffed from Content by the server (http.DetectContentType)
// so evidence can be viewed in a browser.
type Evidence struct {
	ID          string    `json:"id"`
	DeviceID    string    `json:"device_id,omitempty"`
	Kind        string    `json:"kind"`
	SHA256      string    `json:"sha256"`
	ByteSize    int64     `json:"byte_size"`
	ContentType string    `json:"content_type"`
	Content     []byte    `json:"-"`
	CapturedAt  time.Time `json:"captured_at"` // device-claimed capture time
	ReceivedAt  time.Time `json:"received_at"` // server receipt time
}

// Event is something that happened on a device, optionally backed by
// evidence. The ID is generated by the client and acts as the idempotency
// key: resubmitting the same ID replays the original record.
type Event struct {
	ID          string    `json:"id"`
	DeviceID    string    `json:"device_id,omitempty"`
	Type        string    `json:"type"`
	OccurredAt  time.Time `json:"occurred_at"` // device-claimed occurrence time
	ReceivedAt  time.Time `json:"received_at"` // server receipt time
	EvidenceIDs []string  `json:"evidence_ids"`
}
